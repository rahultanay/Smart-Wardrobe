CREATE TABLE IF NOT EXISTS wardrobe_item (
 id VARCHAR(36) PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 category VARCHAR(12) NOT NULL CHECK (category IN ('Shirt','T-shirt','Hoodie','Traditional','Pants','Shoes')),
 color VARCHAR(20) NOT NULL,
 pattern VARCHAR(20) NOT NULL,
 occasions VARCHAR(250) NOT NULL,
 photo CLOB NOT NULL,
 laundry BOOLEAN NOT NULL DEFAULT FALSE,
 archived BOOLEAN NOT NULL DEFAULT FALSE,
 created_at VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS wear_event (
 id VARCHAR(36) PRIMARY KEY,
 worn_at VARCHAR(40) NOT NULL,
 occasion VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS wear_item (
 event_id VARCHAR(36) REFERENCES wear_event(id),
 item_id VARCHAR(36) REFERENCES wardrobe_item(id),
 name_snapshot VARCHAR(80) NOT NULL,
 category_snapshot VARCHAR(12) NOT NULL,
 PRIMARY KEY(event_id,item_id)
);
CREATE TABLE IF NOT EXISTS laundry_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 item_id VARCHAR(36) REFERENCES wardrobe_item(id),
 changed_at VARCHAR(40) NOT NULL,
 in_laundry BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS bulk_import (
 request_id VARCHAR(36) PRIMARY KEY,
 fingerprint VARCHAR(64) NOT NULL,
 item_ids VARCHAR(1000) NOT NULL
);
